TABLA = re.compile(r'(<script id="archify-i18n-data" type="application/json">)(\{.*?\})(</script>)', re.S)

# Marcas y formatos que se quedan como están: no son palabras, son nombres.
INTOCABLES = {"ARCHIFY", "PNG", "SVG", "WebM", "JPEG", "WebP", "SRC", "AUTO"}


def traducir(html: str, lengua: str = "es") -> str:
    """Cambia la tabla de textos del visor por la del idioma pedido.

    `locale` se deja en "en" a propósito: es la etiqueta que el visor conoce y
    no hay razón para meterlo por una rama desconocida; lo que el lector ve sale
    de `messages`, y eso sí va entero en español.
    """
    m = TABLA.search(html)
    if not m:
        return html
    tabla = json.loads(m.group(2))
    originales = dict(tabla["messages"])
    nuevos = ES if lengua == "es" else EN
    tabla["messages"] = {k: nuevos.get(k, v) for k, v in tabla["messages"].items()}
    # Mismo escape que usa Archify al serializar: nada de `<`, `>` ni `&` literales
    # dentro del bloque <script>.
    datos = (json.dumps(tabla, ensure_ascii=False, separators=(",", ":"))
             .replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026"))
    html = html[:m.start()] + m.group(1) + datos + m.group(3) + html[m.end():]
    if lengua == "es":
        html = html.replace('<html lang="en"', '<html lang="es"', 1)
        for patron, reemplazo in COMPILADOS_ES:
            html = patron.sub(reemplazo, html)
        html = _texto_estatico(html, originales)
    return html


# Lo que el compilador escribe en el dibujo con su propio catálogo, no con la
# tabla del visor: el título de la leyenda, la descripción accesible del SVG,
# las etiquetas para lectores de pantalla y el título de la pestaña.
COMPILADOS_ES = (
    (re.compile(r'(<g data-legend=""[^>]*>\s*<text [^>]*>)Legend(</text>)'), r"\1Leyenda\2"),
    (re.compile(r'(<desc id="archify-diagram-description">)A workflow diagram generated by Archify\.(</desc>)'),
     r"\1Diagrama de flujo generado con Archify.\2"),
    (re.compile(r'aria-label="Focus '), 'aria-label="Enfocar '),
    (re.compile(r'(<svg viewBox="[^"]*" role="img") lang="en"'), r'\1 lang="es"'),
    (re.compile(r"<title>([^<]*) Diagram</title>"), r"<title>\1</title>"),
)


def _texto_estatico(html: str, mensajes: dict) -> str:
    """Traduce el texto que el visor trae ya escrito en el marcado.

    La tabla cubre lo que el JavaScript pinta al vuelo, pero la barra y los
    paneles llegan con su texto puesto y el visor no los vuelve a escribir hasta
    que se usan. Aquí se cambian esos, y solo en el cuerpo: tocar la cabecera
    sería tocar el código y las hojas de estilo.

    Se salta lo ambiguo. Si una misma frase inglesa corresponde a dos españolas
    distintas según la clave, no hay forma de saber cuál toca en cada sitio, así
    que se deja como está antes que ponerla mal.
    """
    pares: dict = {}
    for clave, ingles in mensajes.items():
        espanol = ES.get(clave)
        if (not espanol or espanol == ingles or "{" in ingles or len(ingles) < 3
                or ingles in INTOCABLES):
            continue
        pares.setdefault(ingles, set()).add(espanol)
    tabla = {i: next(iter(e)) for i, e in pares.items() if len(e) == 1}

    corte = html.index("<body")
    cabeza, cuerpo = html[:corte], html[corte:]
    # De más larga a más corta, para que "Export diagram" gane a "Export".
    for ingles in sorted(tabla, key=len, reverse=True):
        espanol = tabla[ingles]
        # El marcado escapa el ampersand, y un nodo de texto puede venir con
        # espacios alrededor: `> Export <span`.
        a, b = escape(ingles), escape(espanol)
        cuerpo = re.sub(r">(\s*)%s(\s*)<" % re.escape(a),
                        lambda m: ">%s%s%s<" % (m.group(1), b, m.group(2)), cuerpo)
        for atributo in ("title", "aria-label", "placeholder"):
            cuerpo = cuerpo.replace('%s="%s"' % (atributo, a), '%s="%s"' % (atributo, b))
    return cabeza + cuerpo
